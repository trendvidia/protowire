// protoc-gen-pxf-go generates Go code for lowered RFC-001 schemas on stock
// protobuf. It takes the place of protoc-gen-go and accepts the same options:
//
//	buf generate image.binpb   # plugin: pxf-go
//
// For each file it writes the normal <name>.pb.go, with @description and
// @deprecated surfaced as doc comments, and the RFC-001 §9.3 function stubs to
// <name>_functions.pb.go when the file declares functions.
//
// The comments are set on the in-memory protogen declarations, never on
// SourceCodeInfo, so descriptors stay as the compiler wrote them (§8.5). Stock
// getters do not read a field's comments, so a getter carries neither
// annotation.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime/debug"

	gengo "google.golang.org/protobuf/cmd/protoc-gen-go/internal_gengo"
	"google.golang.org/protobuf/compiler/protogen"
)

func main() {
	if len(os.Args) == 2 && os.Args[1] == "--version" {
		version := "(unknown)"
		if info, ok := debug.ReadBuildInfo(); ok {
			version = info.Main.Version
		}
		fmt.Printf("%v %v\n", filepath.Base(os.Args[0]), version)
		os.Exit(0)
	}
	if len(os.Args) == 2 && os.Args[1] == "--help" {
		fmt.Println("See docs/RFC-001-schema-extensions.md §9.3 for usage information.")
		os.Exit(0)
	}
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		generate(gen)
		return nil
	})
}

// generate writes the output for every file gen asks for.
func generate(gen *protogen.Plugin) {
	types := newSchemaTypes(gen)
	for _, f := range gen.Files {
		if f.Generate {
			generateFile(gen, f, types)
		}
	}
	gen.SupportedFeatures = gengo.SupportedFeatures
	gen.SupportedEditionsMinimum = gengo.SupportedEditionsMinimum
	gen.SupportedEditionsMaximum = gengo.SupportedEditionsMaximum
}

func generateFile(gen *protogen.Plugin, f *protogen.File, types schemaTypes) {
	checkFunctionStubConflict(gen, f)
	annotateFile(f)
	gengo.GenerateFile(gen, f)
	if len(functionStubDecls(f)) > 0 {
		g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+"_functions.pb.go", f.GoImportPath)
		g.P("// Code generated by protoc-gen-pxf-go. DO NOT EDIT.")
		g.P("// source: ", f.Desc.Path())
		g.P()
		g.P("package ", f.GoPackageName)
		g.P()
		genFunctionStubs(g, f, types)
	}
}

// annotateFile copies @description and @deprecated onto the leading comments
// of the declarations in f, which is what protoc-gen-go renders.
func annotateFile(f *protogen.File) {
	for _, e := range f.Enums {
		annotateEnum(e)
	}
	for _, m := range f.Messages {
		annotateMessage(m)
	}
}

func annotateEnum(e *protogen.Enum) {
	e.Comments.Leading = appendSchemaAnnotationComments(e.Comments.Leading, e.Desc.Options())
	for _, v := range e.Values {
		v.Comments.Leading = appendSchemaAnnotationComments(v.Comments.Leading, v.Desc.Options())
	}
}

func annotateMessage(m *protogen.Message) {
	m.Comments.Leading = appendSchemaAnnotationComments(m.Comments.Leading, m.Desc.Options())
	for _, f := range m.Fields {
		f.Comments.Leading = appendSchemaAnnotationComments(f.Comments.Leading, f.Desc.Options())
	}
	for _, o := range m.Oneofs {
		o.Comments.Leading = appendSchemaAnnotationComments(o.Comments.Leading, o.Desc.Options())
	}
	for _, e := range m.Enums {
		annotateEnum(e)
	}
	for _, n := range m.Messages {
		annotateMessage(n)
	}
}
